const TRANSLATIONS: Partial<Record<FaceAgeLanguage, Record<MessageKey, string>>> = {
  en: EN,
  fa: FA,
  ar: AR,
  ur: UR,
  ru: RU,
};

export function translate(language: string, key: MessageKey, vars?: Record<string, string | number>): string {
  const code = mapTelegramLanguage(language);
  const table = TRANSLATIONS[code] ?? EN;
  let text = table[key] ?? EN[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
